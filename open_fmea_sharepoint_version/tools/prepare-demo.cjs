const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const original = fs.readFileSync(path.join(root, 'source/open_fmea_html_demo.html'), 'utf8');
const match = original.match(/<script type="application\/json" id="open-fmea-container">([\s\S]*?)<\/script>/);
if (!match) throw new Error('Embedded container not found');
const container = JSON.parse(match[1]);
const bridge = `
  const hostConfig = window.__openFmeaHostConfig;
  let hostSnapshot = hostConfig.snapshot;
  let hostSequence = 0;
  const localStorage = {
    getItem(key) { return key === 'open_fmea_embedded_container' ? hostSnapshot : null; },
    setItem(key, value) {
      if (key !== 'open_fmea_embedded_container') throw new Error('Unsupported storage key');
      hostSnapshot = String(value);
      parent.postMessage({ channel: 'open-fmea-demo-v1', token: hostConfig.token,
        operation: 'save', snapshot: hostSnapshot, sequence: ++hostSequence }, hostConfig.origin);
    },
    removeItem(key) {
      if (key !== 'open_fmea_embedded_container') return;
      hostSnapshot = null;
      parent.postMessage({ channel: 'open-fmea-demo-v1', token: hostConfig.token,
        operation: 'reset', sequence: ++hostSequence }, hostConfig.origin);
    }
  };
  window.addEventListener('message', event => {
    const m = event.data;
    if (event.source !== parent || event.origin !== hostConfig.origin || !m ||
        m.channel !== 'open-fmea-demo-v1' || m.token !== hostConfig.token) return;
    if (m.operation === 'save-result' && !m.ok) {
      markDirty(true);
      toast('Browser save failed. Export your container to keep your changes. ' + m.error, 'err');
    }
  });
`;
function replaceOnce(text, before, after) {
  if (text.split(before).length !== 2) throw new Error('Expected exactly one source marker: ' + before);
  return text.replace(before, after);
}
let html = replaceOnce(original, 'const OFMEA=(()=>{', 'const OFMEA=(()=>{' + bridge);
html = replaceOnce(html,
  "localStorage.removeItem('open_fmea_embedded_container');location.reload()",
  "localStorage.removeItem('open_fmea_embedded_container')");
html = html.replace('Snapshot saved locally.', 'Snapshot sent to browser storage.');
html = html.replace('<head>', '<head>\n<!--__OPEN_FMEA_HOST_CONFIG__-->');
fs.mkdirSync(path.join(root, 'src/demo'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/demo/demoHtml.ts'),
  '// Generated by tools/prepare-demo.cjs. Edit the source copy, then regenerate.\n' +
  'export const demoHtml: string = ' + JSON.stringify(html) + ';\n');
fs.writeFileSync(path.join(root, 'source/open_fmea.container'), JSON.stringify(container, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'source/provenance.json'), JSON.stringify({
  originalPath: 'D:/Dromation/org/apps/open_fmea/open_fmea_html_version/open_fmea_html_demo.html',
  sha256: crypto.createHash('sha256').update(original).digest('hex'),
  checksumScope: 'English-adapted source copy included in this solution',
  originalSha256: 'b0fa4590c9379eff550f17aa2b9d5f9ccf0dfd3fa80b7300f829890868bc6651',
  sourceChanges: ['Translated three embedded development request phrases from Slovenian into English.'],
  sourceVersion: container.manifest.version,
  conversion: 'SPFx hosted demo; browser snapshots; no SharePoint Lists integration',
  generator: '@microsoft/generator-sharepoint@1.23.2'
}, null, 2) + '\n');
console.log('Prepared demo and portable source container.');
